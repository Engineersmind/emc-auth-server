-- Serves the session list and the active-session count: one row per session now,
-- so neither needs DISTINCT ON over a rotation log.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_user_sessions_live
    ON user_sessions (user_id, tenant_id, last_seen_at DESC)
    WHERE revoked_at IS NULL;

-- +goose StatementEnd

-- +goose StatementBegin

-- Serves the token → session join on every refresh.
CREATE INDEX CONCURRENTLY IF NOT EXISTS idx_refresh_tokens_session
    ON refresh_tokens (session_id);

