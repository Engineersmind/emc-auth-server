-- Safe to reverse: refresh_tokens keeps session_family_id and its own lifecycle
-- columns, which the previous binary reads, so rolling back the code works without
-- restoring data. Only the parent rows are lost.
ALTER TABLE refresh_tokens DROP COLUMN IF EXISTS session_id;
DROP TABLE IF EXISTS user_sessions;

