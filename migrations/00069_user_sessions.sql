-- +goose StatementBegin

-- Advance the identity sequence past every explicitly-inserted id, or the first
-- new session would collide with a backfilled one.
SELECT setval(
    pg_get_serial_sequence('user_sessions', 'id'),
    GREATEST((SELECT COALESCE(MAX(id), 0) FROM user_sessions), 1)
);

